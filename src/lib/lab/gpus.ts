export const GPU_BY_ID: Record<GpuId, Gpu> = Object.fromEntries(
  GPUS.map((g) => [g.id, g]),
) as Record<GpuId, Gpu>;

/** Nearest discrete card by VRAM, used as a speed reference for a custom budget. */
export function nearestDiscreteGpu(vramGB: number): Gpu {
  return [...GPUS]
    .filter((g) => !g.unifiedMemGB)
    .sort((a, b) => Math.abs(a.vramGB - vramGB) - Math.abs(b.vramGB - vramGB))[0];
}

